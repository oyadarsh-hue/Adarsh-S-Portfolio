const educationSlugs = new Set(['sslc', 'hse', 'bsc', 'mca', 'journey']);
const projectKeys = new Map([['epigraphix-ai', 'manuscript'], ['publication', 'manuscript'], ['quietnote', 'quietnote']]);

function localizedTerm(key, code) {
  const tag = language(code);
  if (!tag || !key) return null;
  const locale = [tag, equivalentTag(tag), baseFallback(tag)].find(value => Object.hasOwn(copy, value));
  return locale ? copy[locale][key] : null;
}

export function educationTerm(slug, code) {
  return educationSlugs.has(slug) ? localizedTerm(slug, code) : null;
}

export function projectTerm(slug, code) {
  return localizedTerm(projectKeys.get(slug), code);
}
